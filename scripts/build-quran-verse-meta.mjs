/**
 * Fetches verse metadata (page, juz, hizb) from api.quran.com and writes
 * `src/lib/quran/verse-meta.generated.ts` for offline use (1..6236).
 * Run: node scripts/build-quran-verse-meta.mjs
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const VERSES_PER_SURAH = [
  7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110, 98, 135, 112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34, 30, 73, 54, 45, 83, 182, 88, 75, 85, 54, 53, 89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96, 29, 22, 24, 13, 14, 11, 11, 18, 12, 12, 30, 52, 52, 44, 28, 28, 20, 56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17,   19, 26, 30, 20, 15, 21, 11, 8, 8, 19, 5, 8, 8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
];

const PREFIX = [0];
let acc = 0;
for (const n of VERSES_PER_SURAH) {
  acc += n;
  PREFIX.push(acc);
}

function globalAyahIndex(surah, ayah) {
  return PREFIX[surah - 1] + ayah;
}

async function fetchChapterVerses(chapter) {
  const out = [];
  let page = 1;
  for (;;) {
    const url = `https://api.quran.com/api/v4/verses/by_chapter/${chapter}?words=false&fields=verse_key,page_number,juz_number,hizb_number&per_page=50&page=${page}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status} chapter ${chapter} page ${page}`);
    const j = await res.json();
    const verses = j.verses ?? [];
    out.push(...verses);
    if (!j.pagination?.next_page) break;
    page = j.pagination.next_page;
  }
  return out;
}

async function main() {
  const pages = new Uint16Array(PREFIX[114] + 1);
  const juzs = new Uint8Array(PREFIX[114] + 1);
  const hizbs = new Uint8Array(PREFIX[114] + 1);

  for (let ch = 1; ch <= 114; ch++) {
    const verses = await fetchChapterVerses(ch);
    for (const v of verses) {
      const [s, a] = String(v.verse_key).split(":").map(Number);
      const g = globalAyahIndex(s, a);
      pages[g] = v.page_number ?? 0;
      juzs[g] = v.juz_number ?? 0;
      hizbs[g] = v.hizb_number ?? 0;
    }
    process.stderr.write(`chapter ${ch}/114\r`);
  }

  for (let g = 1; g <= PREFIX[114]; g++) {
    if (pages[g] === 0) throw new Error(`missing page at global ${g}`);
  }

  const outPath = resolve("src/lib/quran/verse-meta.generated.ts");
  const body = `// AUTO-GENERATED by scripts/build-quran-verse-meta.mjs — do not edit by hand.
export const VERSE_COUNT = ${PREFIX[114]} as const;

/** 1-based global ayah index → Madani mushaf page (api.quran.com). */
export const VERSE_PAGE = new Uint16Array(${JSON.stringify([...pages])});

/** 1-based global ayah index → Juz 1..30 */
export const VERSE_JUZ = new Uint8Array(${JSON.stringify([...juzs])});

/** 1-based global ayah index → Hizb 1..60 */
export const VERSE_HIZB = new Uint8Array(${JSON.stringify([...hizbs])});
`;
  writeFileSync(outPath, body, "utf8");
  process.stderr.write(`\nWrote ${outPath}\n`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
