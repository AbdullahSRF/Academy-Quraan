export function surahArShortName(surahNumber: number): string {
  if (surahNumber < 1 || surahNumber > 114) {
    throw new Error(`surah out of range: ${surahNumber}`);
  }
  return SURAH_NAMES_AR[surahNumber - 1]!;
}

/** مثال: سورة البقرة (2) */
export function formatSurahWithNumber(surahNumber: number): string {
  return `سورة ${surahArShortName(surahNumber)} (${surahNumber})`;
}

/** مثال: سورة البقرة (2) — آية 5 */
export function formatSurahAyahLine(surahNumber: number, ayahNumber: number): string {
  return `${formatSurahWithNumber(surahNumber)} — آية ${ayahNumber}`;
}
